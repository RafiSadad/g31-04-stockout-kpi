"""Step 5: write the data dictionary and the cleaning log.

Outputs: docs/data_dictionary.md, docs/cleaning_log.md, and the sheets Data_dictionary and Cleaning_log
in outputs/G31-04 KPI Tables.xlsx (other sheets, including Reconcile, are not touched).
Example values are read from the data, never typed by hand. Only small parts of the raw CSVs are read.
"""
import pandas as pd
from config import DATA_DIR, WORK_DIR, OUT_DIR, DOCS_DIR
from cleanlog import PATH as LOG_PATH
from dictionary_spec import SPEC

DOCS = DOCS_DIR
XLSX = OUT_DIR / "G31-04 KPI Tables.xlsx"


# ---------- one real example row per table ----------
small = pd.read_csv(WORK_DIR / "item_props_small.csv.gz", nrows=200_000, dtype={"value": "string"})
ip_row = small[small["property"] == "available"].iloc[0]
ev = pd.read_csv(DATA_DIR / "events.csv", nrows=200_000)
ev_row = ev.iloc[0]
ex = {"item_properties (part1 + part2)": {c: str(ip_row[c]) for c in ip_row.index},
      "events": {c: str(ev_row[c]) for c in ("timestamp", "visitorid", "event", "itemid")}}
tid = ev["transactionid"].dropna()
ex["events"]["transactionid"] = "" if tid.empty else str(int(tid.iloc[0]))  # first non-empty one (purchases only)
ct = pd.read_csv(DATA_DIR / "category_tree.csv")
ct_row = ct.dropna().iloc[0]
ex["category_tree"] = {"categoryid": str(int(ct_row["categoryid"])), "parentid": str(int(ct_row["parentid"]))}
mt = pd.read_csv(WORK_DIR / "modelling_table_features.csv.gz")
# from 7 Jun on, the 28-day window lies fully inside the data (starts 3 May), so 4w features are not partial
pick = mt[(mt["snapshot"] >= "2015-06-07") & (mt["tx_4w"] > 0) & (mt["cat_missing"] == 0) & mt["days_since_last_tx"].notna()]
mt_row = (pick if len(pick) else mt).iloc[0]
mt_key = [k for k in SPEC if k.startswith("modelling table")][0]
ex[mt_key] = {c: (f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)) for c, v in mt_row.items()}

# check that the spec covers exactly the columns of the modelling table
spec_cols = [c[0] for c in SPEC[mt_key]]
all_cols = list(pd.read_csv(WORK_DIR / "modelling_table_features.csv.gz", nrows=0).columns)
missing, extra = set(all_cols) - set(spec_cols), set(spec_cols) - set(all_cols)
if missing or extra:
    raise SystemExit(f"dictionary_spec.py is out of date. Not described: {sorted(missing)}. Not in the table: {sorted(extra)}")

rows = []
for table, cols in SPEC.items():
    for col, typ, meaning, used, why in cols:
        rows.append({"table": table, "column": col, "type": typ, "meaning": meaning,
                     "example": ex.get(table, {}).get(col, ""), "used": used, "why": why})
dd = pd.DataFrame(rows)

# ---------- markdown ----------
def md_table(df):
    out = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(v).replace("|", "/") for v in r) + " |")
    return "\n".join(out)

lines = ["# Data dictionary", "",
         "Generated by `scripts/05_docs.py` from `scripts/dictionary_spec.py`. Do not edit by hand: change the spec and rerun.",
         "Example values come from the data (first suitable row). In the modelling table all examples come from the same row.",
         "Windows: 1w = (t - 7 days, t], 4w = (t - 28 days, t], t = snapshot time. All features use events at or before t only.", ""]
for table in SPEC:
    lines += [f"## {table}", "", md_table(dd[dd["table"] == table].drop(columns="table")), ""]
(DOCS / "data_dictionary.md").write_text("\n".join(lines))

cl = pd.read_csv(LOG_PATH)
cl_lines = ["# Cleaning log", "",
            "Generated by `scripts/05_docs.py` from `work/cleaning_log.csv` (written by steps 1, 3 and 4). Rows x columns before and after each step.",
            "A `0 x 0` before means the table is read from file in that step.", "",
            md_table(cl.fillna("")), ""]
(DOCS / "cleaning_log.md").write_text("\n".join(cl_lines))

# ---------- workbook sheets ----------
with pd.ExcelWriter(XLSX, mode="a", engine="openpyxl", if_sheet_exists="replace") as xw:
    dd.to_excel(xw, sheet_name="Data_dictionary", index=False)
    cl.to_excel(xw, sheet_name="Cleaning_log", index=False)
print("wrote docs/data_dictionary.md, docs/cleaning_log.md and 2 sheets in", XLSX)
print(cl[["script", "step", "action", "rows_before", "cols_before", "rows_after", "cols_after"]].to_string(index=False))
